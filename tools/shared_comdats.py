#!/usr/bin/env python3
"""Find COMDAT constants (__real@..., ??_C@... strings, ...) that libraries share
with game code.

LINK keeps the first definition of a "select any" COMDAT, and game objects
come first, so a float constant or string literal that both the game and a
library use lives in the game's .rdata. The blobs must define those COMDATs
(by name, at the original place) or the library's copy gets placed instead.

For every relocation in an identified library function that targets a COMDAT
data symbol, the original address is read from wf.exe; targets inside game
ranges are written to config/comdats.txt, together with the hand-found
entries of config/comdats-manual.txt.
"""
import csv
import os
import struct

from splits import load_splits
from wfcommon import BUILD, CONFIG, ORIG_EXE, PE, VC71, Coff, coff_members


def lib_objects():
    for d in sorted(os.listdir(os.path.join(BUILD, "lib"))):
        p = os.path.join(BUILD, "lib", d)
        if os.path.isdir(p) and d != "src":
            for fn in sorted(os.listdir(p)):
                if fn.endswith(".obj"):
                    yield Coff(open(os.path.join(p, fn), "rb").read(), fn)
    yield from coff_members(f"{VC71}/lib/libcmt.lib")


def main():
    pe = PE(ORIG_EXE)
    sp = load_splits()
    funcs = {}
    for r in csv.DictReader(open(os.path.join(CONFIG, "library-symbols.csv"))):
        funcs.setdefault(r["name"], int(r["address"], 16))
    found = {}
    for c in lib_objects():
        # names of COMDAT data symbols in this object
        comdat_syms = {}
        for s in c.symlist:
            if 0 < s["section"] <= len(c.sections):
                sec = c.sections[s["section"] - 1]
                if sec["comdat"] and not sec["flags"] & 0x20 and s["cls"] == 2:
                    comdat_syms[s["index"]] = (s["name"], sec["size"])
        if not comdat_syms:
            continue
        for sec in c.sections:
            if not sec["flags"] & 0x20:
                continue
            fsyms = [y for y in sec["syms"] if y["type"] & 0x20 and y["name"] in funcs]
            for y in fsyms:
                base = funcs[y["name"]] - y["value"]
                for off, symidx, typ in sec["rels"]:
                    if symidx not in comdat_syms or typ != 6:
                        continue
                    name, size = comdat_syms[symidx]
                    addend = struct.unpack_from("<I", sec["data"], off)[0]
                    t = pe.u32(base + off) - addend
                    if sp.unit_of(t):
                        found.setdefault(t, {})[name] = size
    manual = os.path.join(CONFIG, "comdats-manual.txt")
    if os.path.exists(manual):
        for line in open(manual):
            f = line.split("#", 1)[0].split()
            if f:
                found.setdefault(int(f[0], 16), {})[f[1]] = int(f[2], 16)
    with open(os.path.join(CONFIG, "comdats.txt"), "w") as fp:
        fp.write("# COMDAT constants defined by game code and shared with libraries\n")
        fp.write("# (generated by tools/shared_comdats.py)  address name size\n")
        for t in sorted(found):
            for name, size in sorted(found[t].items()):
                fp.write(f"{t:08x} {name} {size:x}\n")
    print(f"{len(found)} shared COMDATs")


if __name__ == "__main__":
    main()
